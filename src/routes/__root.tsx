function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="pt-BR">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  // Persiste catálogo/configurações no localStorage para abrir rápido
  // mesmo com conexão ruim (cache válido por 7 dias).
  const persister = useMemo(() => {
    if (typeof window === "undefined") return undefined;
    return createAsyncStoragePersister({
      storage: window.localStorage,
      key: "ng-catalog-cache",
    });
  }, []);

  // Registra o service worker que faz cache das bandeiras.
  useEffect(() => {
    if ("serviceWorker" in navigator) {
      navigator.serviceWorker.register("/sw.js").catch(() => {});
    }
  }, []);

  const outlet = (
    <>
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <Outlet />
      <Toaster position="top-right" richColors />
      <PwaInstallPrompt />
    </>
  );

  if (!persister) {
    return <QueryClientProvider client={queryClient}>{outlet}</QueryClientProvider>;
  }

  return (
    <PersistQueryClientProvider
      client={queryClient}
      persistOptions={{
        persister,
        maxAge: 7 * 24 * 60 * 60_000,
        dehydrateOptions: {
          shouldDehydrateQuery: (q) =>
            q.queryKey[0] === "app_settings" || q.queryKey[0] === "country_overrides",
        },
      }}
    >
      {outlet}
    </PersistQueryClientProvider>
  );
}
